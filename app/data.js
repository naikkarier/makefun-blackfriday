// Derived numbers, computed here so the page and the cards always agree.
export function discountOf(deal) {
  return Math.round((1 - deal.sale / deal.was) * 100);
}

export function savedOf(deal) {
  return Math.round((deal.was - deal.sale) * 100) / 100;
}

export function money(n) {
  return "$" + n.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}
